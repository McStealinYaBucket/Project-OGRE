"""Generate link stubs for functions the tree calls but nobody has written yet.

Run from the repo root after a build (needs llvm-undname on PATH):
    python3 -P tools/gen_link_stubs.py              # build/, both targets
    python3 -P tools/gen_link_stubs.py --build B    # another build directory
    python3 -P tools/gen_link_stubs.py --selftest
then rebuild (cmake --build build) and regenerate the CSVs.

How it works. The script reruns each exe's bare link.exe command (vs_link_exe hides its output) and reads the
LNK2001/LNK2019 lines /FORCE:UNRESOLVED leaves. For every unresolved *function* it looks up the
original's address in ida/exports/<T>-names.csv: the MSVC-decorated name first (match:/lib:/flirt:
rows), else the demangled qualified name + parameter count + const against the ios:/mac:/prior: rows
(a unique address only; a name alone is not enough: RobloxExtraSpace() and RobloxExtraSpace(parent)
share one, and only the second has an oracle row). Each address gets one
function in Client/_generated/<target>/stubs_NN.cpp:

    // STUB: PLAYER 0x00412340
    extern "C" void ogre_stub_00412340() { STUB(0x00412340); }
    #pragma comment(linker, "/alternatename:?foo@Bar@RBX@@QAEXH@Z=_ogre_stub_00412340")

/alternatename binds the unresolved decorated name to the stub only while nothing else defines it,
so a stub can never collide with a real definition. STUB() stores a distinct constant, so /OPT:ICF
cannot fold two stubs. reccmp pairs the stub with the original address through its marker, so every
call site that reaches it shows as paired. Each exe links only its own target's stubs.

Rerunning is incremental: stubs whose name the exe's map now defines elsewhere (someone wrote the
function) are dropped, stubs still needed are kept, newly unresolved functions are added.
Unresolved data and functions with no known address stay with /FORCE:UNRESOLVED; their list goes to
Client/_generated/<target>/unresolved.txt. link.exe's full output is kept in <build>/<exe>.link.log. Never edit Client/_generated by hand.
"""
import argparse
import collections
import csv
import glob
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "Client", "_generated")
EXES = {"PLAYER": "RobloxPlayerBeta.exe", "STUDIO": "RobloxStudioBeta.exe"}
PER_FILE = 400

UNRES = re.compile(r'unresolved external symbol (?:"[^"]*" \((\S+)\)|(\S+))')
ALT = re.compile(r'/alternatename:(\S+)=_ogre_stub_([0-9a-f]{8})')
CC = re.compile(r'\b__(?:thiscall|cdecl|stdcall|fastcall|clrcall)\b')


def undname(names):
    out = {}
    names = list(names)
    for i in range(0, len(names), 300):
        chunk = names[i:i + 300]
        text = subprocess.run(["llvm-undname"] + chunk, capture_output=True, text=True).stdout
        for block in text.strip().split("\n\n"):
            lines = block.split("\n")
            if len(lines) >= 2:
                out[lines[0]] = lines[1]
    return out


def split_sig(dem):
    """'public: int __thiscall RBX::Bar::foo(int, class X *) const' -> ('RBX::Bar::foo', 2, True).
    Works for llvm-undname and Itanium (c++filt) spellings. None for data."""
    dem = re.sub(r" \[[^\]]*\]$", "", dem.strip())  # names.csv's '[D0, deleting: ...]' notes
    is_const = bool(re.search(r"\)\s*const\s*$", dem))
    body = re.sub(r"\s*const\s*$", "", dem)
    if not body.endswith(")"):
        return None
    depth, i = 0, len(body) - 1
    while i >= 0:  # the last top-level (...) is the parameter list
        c = body[i]
        if c in ")>":
            depth += 1
        elif c in "(<":
            depth -= 1
            if depth == 0 and c == "(":
                break
        i -= 1
    if i <= 0:
        return None
    params, head = body[i + 1:-1].strip(), body[:i]
    if head.endswith("operator"):  # operator()(...)
        return None
    m = list(CC.finditer(head))
    if m:
        head = head[m[-1].end():]
    else:  # Itanium: drop a return type (the last top-level space splits it off)
        depth, cut = 0, -1
        for j, c in enumerate(head):
            if c in "<(":
                depth += 1
            elif c in ">)":
                depth -= 1
            elif c == " " and depth == 0 and not head[j + 1:].startswith("operator") and \
                    not head[:j].endswith("operator"):
                cut = j
        head = head[cut + 1:]
    name = norm(head)
    if params in ("", "void"):
        n = 0
    else:
        depth, n = 0, 1
        for c in params:
            if c in "<(":
                depth += 1
            elif c in ">)":
                depth -= 1
            elif c == "," and depth == 0:
                n += 1
    return name, n, is_const


def norm(s):
    s = s.replace("`anonymous namespace'", "anon").replace("(anonymous namespace)", "anon")
    s = re.sub(r"\b(class|struct|enum|union)\s+", "", s)
    return re.sub(r"\s+", "", s)


def oracle(target):
    """decorated -> addr, (name, nparams, const) -> {addr}, name -> {addr}, plus ctor/dtor flavour."""
    exact, bykey, byname = {}, collections.defaultdict(set), collections.defaultdict(set)
    path = os.path.join(ROOT, "ida", "exports", f"{target}-names.csv")
    for r in csv.DictReader(open(path, newline="")):
        if r["kind"] != "func":
            continue
        src = r["source"].split(":")[0]
        addr = int(r["address"], 16)
        exact.setdefault(r["name"], addr)  # MSVC-decorated, or a C name (Mach-O keeps the '_')
        if r["name"].startswith("?"):
            continue
        if src not in ("ios", "mac", "prior") or "D0Ev" in r["name"] or "[D0" in r["demangled"]:
            continue
        sig = split_sig(r["demangled"])
        if sig:
            bykey[sig].add(addr)
            byname[sig[0]].add(addr)
    return exact, bykey, byname


def claimed(target):
    """Addresses already owned by a marker outside Client/_generated or by a reccmp CSV row with a
    symbol or name: a stub there would be a second claim (the real definition's signature differs
    from the caller's declaration, which is a source bug to fix, not to stub)."""
    out = set()
    mk = re.compile(r"//\s*(?:FUNCTION|STUB|TEMPLATE|SYNTHETIC|LIBRARY):\s*" + target + r"\s+0x([0-9a-fA-F]+)")
    for dirpath, dirs, files in os.walk(os.path.join(ROOT, "Client")):
        if os.path.abspath(dirpath).startswith(GEN):
            continue
        for fn in files:
            if fn.endswith((".cpp", ".c", ".h", ".hpp", ".inl")):
                for m in mk.finditer(open(os.path.join(dirpath, fn), errors="replace").read()):
                    out.add(int(m.group(1), 16))
    for p in glob.glob(os.path.join(ROOT, "reccmp", f"{target.lower()}-*.csv")):
        if p.endswith(("-function-size.csv", "-symbols.csv", "-imports.csv")):
            continue
        for r in csv.reader(l for l in open(p) if not l.startswith("#")):
            if r and re.fullmatch(r"[0-9a-fA-F]{8}", r[0]):
                out.add(int(r[0], 16))
    return out


def lookup(dec, dem, ora):
    exact, bykey, byname = ora
    if dec in exact:
        return exact[dec], "exact"
    sig = split_sig(dem) if dem else None
    if not sig:
        return None, "data" if dem and "(" not in dem else "unparsed"
    for cands, how in ((bykey.get(sig), "sig"),
                       (bykey.get((sig[0], sig[1], not sig[2])), "sig-noconst")):
        if cands and len(cands) == 1:
            return next(iter(cands)), how
        if cands:
            return None, "ambiguous"
    return None, "unknown"


def link_output(build, exe):
    """Reruns exe's bare link.exe command (main() first builds with ninja -d keeprsp so its response
    file exists): CMake's vs_link_exe wrapper prints link.exe's output only when the link fails."""
    cmd = subprocess.run(["ninja", "-C", build, "-t", "commands", exe], capture_output=True, text=True,
                         check=True).stdout.strip().split("\n")[-1]
    inner = cmd.split(" -- ", 1)[1].rsplit(" && :", 1)[0]
    out = subprocess.run(inner, shell=True, cwd=build, capture_output=True, text=True)
    return out.stdout + out.stderr


def map_publics(path):
    names = set()
    for line in open(path, errors="replace"):
        f = line.split()
        # /alternatename aliases show up in the map under the stub's own object: not a definition
        if len(f) >= 3 and re.fullmatch(r"[0-9a-f]{4}:[0-9a-f]{8}", f[0]) and \
                not re.fullmatch(r"stubs_\d+\.cpp\.obj", f[-1]):
            names.add(f[1])
    return names


def existing(target):
    stubs = collections.defaultdict(set)
    for p in glob.glob(os.path.join(GEN, target.lower(), "stubs_*.cpp")):
        for m in ALT.finditer(open(p).read()):
            stubs[int(m.group(2), 16)].add(m.group(1))
    return stubs


def write(target, stubs, dem, left):
    d = os.path.join(GEN, target.lower())
    os.makedirs(d, exist_ok=True)
    for p in glob.glob(os.path.join(d, "stubs_*.cpp")):
        os.remove(p)
    addrs = sorted(stubs)
    for k in range(0, max(len(addrs), 1), PER_FILE):
        lines = [f"// GENERATED by tools/gen_link_stubs.py from the {target} link's unresolved externals.",
                 "// Do not edit: rerun the script. Each stub stands in for a function nobody has written",
                 "// yet, so that calls to it pair with the original callee.",
                 '#include "decomp.h"', ""]
        for a in addrs[k:k + PER_FILE]:
            for dec in sorted(stubs[a]):  # above the marker: a comment below it would be a nameref
                lines.append(f"// {dem.get(dec, dec)}")
            lines.append(f"// STUB: {target} 0x{a:08x}")
            lines += [f'extern "C" void ogre_stub_{a:08x}()', "{", f"\tSTUB(0x{a:08x});", "}"]
            for dec in sorted(stubs[a]):
                lines.append(f'#pragma comment(linker, "/alternatename:{dec}=_ogre_stub_{a:08x}")')
            lines.append("")
        open(os.path.join(d, f"stubs_{k // PER_FILE:02d}.cpp"), "w").write("\n".join(lines))
    with open(os.path.join(d, "unresolved.txt"), "w") as f:
        f.write(f"# {target}: unresolved externals with no stub (reason, decorated, demangled). Generated.\n")
        for dec, why in sorted(left.items(), key=lambda x: (x[1], x[0])):
            f.write(f"{why}\t{dec}\t{dem.get(dec, '')}\n")


def gen(target, build):
    exe = EXES[target]
    text = link_output(build, exe)
    with open(os.path.join(build, exe[:-4] + ".link.log"), "w") as f:  # the full link output, kept
        f.write(text)
    unres = {m.group(1) or m.group(2) for m in UNRES.finditer(text)}
    defined = map_publics(os.path.join(build, exe[:-4] + ".map"))
    stubs = existing(target)
    dropped = 0
    for a in list(stubs):
        keep = {d for d in stubs[a] if d not in defined}
        dropped += len(stubs[a]) - len(keep)
        if keep:
            stubs[a] = keep
        else:
            del stubs[a]
    dem = undname(unres | {d for s in stubs.values() for d in s})
    ora = oracle(target)
    owned = claimed(target)
    why = collections.Counter()
    left = {}
    taken = {d for s in stubs.values() for d in s}
    for dec in sorted(unres - taken):
        if dec.startswith("__imp_"):
            left[dec] = "import"
            why["import"] += 1
            continue
        addr, how = lookup(dec, dem.get(dec), ora)
        if addr is not None and addr in owned:
            addr, how = None, "claimed"
        why[how] += 1
        if addr is None:
            left[dec] = how
        else:
            stubs[addr].add(dec)
    write(target, stubs, dem, left)
    print(f"{target}: {len(unres)} unresolved in this link; stubs now {len(stubs)} addresses / "
          f"{sum(len(s) for s in stubs.values())} names (dropped {dropped} now defined); "
          f"no stub {len(left)}; " + ", ".join(f"{k} {v}" for k, v in why.most_common()))


def selftest():
    assert split_sig("public: int __thiscall RBX::Bar::foo(int, class RBX::X *) const") == ("RBX::Bar::foo", 2, True)
    assert split_sig("RBX::Bar::foo(int, RBX::X*) const") == ("RBX::Bar::foo", 2, True)
    assert split_sig("void boost::f<RBX::A, int>(RBX::A*)") == ("boost::f<RBX::A,int>", 1, False)
    assert split_sig("private: __thiscall RobloxExtraSpace::RobloxExtraSpace(void)") == \
        ("RobloxExtraSpace::RobloxExtraSpace", 0, False)
    assert split_sig("RBX::Foo::~Foo() [D2]") == ("RBX::Foo::~Foo", 0, False)
    assert split_sig("bool RBX::operator==(RBX::A const&, RBX::A const&)") == ("RBX::operator==", 2, False)
    assert split_sig("int x") is None
    m = UNRES.search('error LNK2019: unresolved external symbol "public: void __thiscall A::f(void)" '
                     '(?f@A@@QAEXXZ) referenced in function _main')
    assert m.group(1) == "?f@A@@QAEXXZ"
    assert UNRES.search("LNK2001: unresolved external symbol _foo").group(2) == "_foo"
    print("selftest ok")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default=os.path.join(ROOT, "build"))
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("targets", nargs="*", default=list(EXES))
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    build = os.path.abspath(a.build)
    subprocess.run(["ninja", "-C", build, "-d", "keeprsp"] + [EXES[t] for t in a.targets],
                   capture_output=True, check=True)
    for t in a.targets:
        gen(t, build)


if __name__ == "__main__":
    main()
